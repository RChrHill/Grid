// End-to-end LLR run with replica exchange
// Run with e.g. mpirun -np 2 ./Test_llr_replica_exchange_hmc --grid 4.4.4.4 --mpi 1.1.1.2 --replicas 2 --Trajectories 100

#include <Grid/Grid.h>
#include <Grid/qcd/llr/ReplicaExchangeModule.h>
#include <Grid/qcd/llr/ReplicaGrids.h>
#include <Grid/qcd/llr/ScopedWorldCommunicator.h>

int main(int argc, char **argv)
{
    using namespace Grid;

    Grid_init(&argc, &argv);
    GridLogLayout();

    int replica_count = 2;
    if (GridCmdOptionExists(argv, argv + argc, "--replicas"))
    {
        std::string arg = GridCmdOptionPayload(argv, argv + argc, "--replicas");
        GridCmdOptionInt(arg, replica_count);
    }

    // The grid containing all replicas.
    std::unique_ptr<GridCartesian> full_grid(SpaceTimeGrid::makeFourDimGrid(GridDefaultLatt(), GridDefaultSimd(Nd, vComplex::Nsimd()), GridDefaultMpi()));

    typedef GenericHMCRunner<MinimumNorm2> HMCWrapper;
    HMCWrapper TheHMC;

    // Set the 'gauge' Grid to that of the split grid generated by the ReplicaGridModule.
    int replica_index = -1;
    GridModule replica_module = ReplicaGridModule(*full_grid, replica_count, replica_index);
    TheHMC.Resources.AddGrid("gauge", replica_module);
    GridCartesian &replica_grid = *TheHMC.Resources.GetCartesian("gauge");
    std::string replica_tag = std::to_string(replica_index);

    // Checkpoints are per-replica, so give them distinct names.+
    CheckpointerParameters CPparams;
    CPparams.config_prefix = "ckpoint_lat_replica" + replica_tag;
    CPparams.rng_prefix    = "ckpoint_rng_replica" + replica_tag;
    CPparams.saveInterval  = 65535;
    CPparams.format        = "IEEE64BIG";
    TheHMC.Resources.LoadNerscCheckpointer(CPparams);

    // Same applies to RNGs.
    RNGModuleParameters RNGpar;
    RNGpar.serial_seeds   = "1 2 3 4 5 " + replica_tag;
    RNGpar.parallel_seeds = "6 7 8 9 10 " + replica_tag;
    TheHMC.Resources.SetRNGSeeds(RNGpar);

    typedef PlaquetteMod<HMCWrapper::ImplPolicy> PlaqObs;
    TheHMC.Resources.AddObservable<PlaqObs>();

    // Define a bunch of intervals spanning the replicas.
    RealD S0_centre  = 768;
    RealD S0_spacing = 6.0;
    auto interval_S0 = [&](int interval) { return S0_centre + S0_spacing * (interval - 0.5 * (replica_count - 1)); };

    // Set up the constrained action.
    WilsonGaugeActionR bare_action(1.0);
    typedef ConstrainedAction<WilsonGaugeActionR> ConstrainedWilsonGaugeAction;
    ConstrainedActionParameters action_parameters{.a=5.5, .S0=interval_S0(replica_index), .sigma=3.0};
    ConstrainedWilsonGaugeAction constrained_action(bare_action, action_parameters);
    typedef RobbinsMonroSolver<ConstrainedWilsonGaugeAction> Solver;
    Solver solver(constrained_action, RobbinsMonroParameters(50, 10, 5, 1.0));

    // Set up the exchange RNG.
    GridSerialRNG exchange_rng;
    exchange_rng.SeedFixedIntegers({11, 12, 13, 14, 15});
    int steps_between_exchanges = 5;
    typedef LLRReplicaExchangeModule<Solver> ExchangeMod;
    TheHMC.Resources.AddObservable<ExchangeMod>(*full_grid, replica_grid, replica_index, replica_index, solver, steps_between_exchanges, exchange_rng);

    ActionLevel<HMCWrapper::Field> Level1(1);
    Level1.push_back(&constrained_action);
    TheHMC.TheAction.push_back(Level1);

    TheHMC.Parameters.Trajectories      = 200;
    TheHMC.Parameters.NoMetropolisUntil = 0;
    TheHMC.Parameters.MD.MDsteps        = 100;
    TheHMC.Parameters.MD.trajL          = 1.0;
    TheHMC.ReadCommandLine(argc, argv);

    {
        // Confine the HMC's RNG seeding and draws to this replica, so that replicas evolve independently.
        // The restriction is removed outside this scope, so that replicas can attempt an exchange.
        ScopedWorldCommunicator replica_scope(replica_grid);
        TheHMC.Run();
    }

    // Get the exchange module -- 'getNamedObservable' will really help tidy this mess up.
    ExchangeMod *exchange_module = nullptr;
    for (HmcObservable<HMCWrapper::Field> *observable : TheHMC.Resources.GetObservables())
    {
        if (ExchangeMod *candidate = dynamic_cast<ExchangeMod *>(observable))
        {
            exchange_module = candidate;
        }
    }
    assert(exchange_module != nullptr);

    int final_trajectory = TheHMC.Parameters.StartTrajectory + TheHMC.Parameters.NoMetropolisUntil + TheHMC.Parameters.Trajectories;
    assert(exchange_module->exchange_attempt_count() == final_trajectory / steps_between_exchanges);

    assert(constrained_action.parameters().S0 == interval_S0(exchange_module->interval_index()));

    std::cout << GridLogMessage << "Replica " << replica_index << " finished with interval " << exchange_module->interval_index()
              << ", a = " << constrained_action.parameters().a << ", S0 = " << constrained_action.parameters().S0 << std::endl;

    Grid_finalize();
}

